using System.Collections.Generic;
using System.Linq;
using CloudGarden.Integration;
using NUnit.Framework;
using Oculus.Interaction.Input;
using UnityEditor;
using UnityEngine;

namespace ShapeOfMemory.Tests
{
    // Playtest 2026-11-16: a hand that lost tracking stayed drawn, frozen where it was lost. Both rigs' hand chains run
    // through the Interaction SDK's LastKnownGoodHand, which keeps reporting a lost hand as tracked at its last pose, so
    // MetaShadowPlayer.Seen asks the chain's raw source and lets the hand go LostAfter after that source drops it.
    public class HandSightTests
    {
        [Test] public void AHandOutOfViewGoesAfterAMomentAndComesBackAtOnce()
        {
            var s=new MetaShadowPlayer.Sight();float lost=MetaShadowPlayer.LostAfter;
            Assert.IsFalse(s.Seen,"not seen before it is tracked");
            Assert.IsTrue(s.Step(true,true,0));Assert.IsTrue(s.Seen,"tracked: seen");
            Assert.IsFalse(s.Step(true,false,.1f),"its source drops it");Assert.IsTrue(s.Seen,"still drawn that frame");
            s.Step(true,false,.1f+lost*.9f);Assert.IsTrue(s.Seen,"a dropped frame or two doesn't blink it");
            Assert.IsTrue(s.Step(true,false,.1f+lost*1.05f));Assert.IsFalse(s.Seen,"held by the rig past LostAfter: gone");
            s.Step(true,false,5);Assert.IsFalse(s.Seen,"and stays gone while the rig holds its last pose");
            Assert.IsTrue(s.Step(true,true,5.01f));Assert.IsTrue(s.Seen,"back in view: at once");
            s.Step(true,false,6);s.Step(true,true,6.05f);s.Step(true,false,6.06f);s.Step(true,false,6.06f+lost*.9f);
            Assert.IsTrue(s.Seen,"each loss gets its own grace");
            Assert.IsTrue(s.Step(false,false,7));Assert.IsFalse(s.Seen,"no hand at all (untracked, head away): gone at once");
            s.Step(true,false,7.01f);Assert.IsFalse(s.Seen,"a held pose never brings back a hand that was gone");
        }

        // Each rig's hand chain (prefab contents, not a scene): the hand the game reads runs through LastKnownGoodHand
        // from the runtime's hand tracking, which is why Seen asks the raw source. The UnityXR rig's controller-made hands
        // root at a ControllerHandDataSource, which MetaShadowPlayer never takes for a hand.
        [TestCase("Assets/MetaHackthone/Generated/PicoPlayer.prefab","UnityXRHands","FromUnityXRHandDataSource",true)]
        [TestCase("Assets/CloudGarden/Prefabs/MetaHackathonPlayer.prefab","OVRHands","FromOVRHandDataSource",false)]
        public void TheRigsHandsComeThroughLastKnownGoodHand(string rig,string handsName,string raw,bool controllerHands)
        {
            if(!AssetDatabase.LoadAssetAtPath<GameObject>(rig))Assert.Ignore(rig+" is missing (PicoPlayer is generated by the Pico build)");
            var root=PrefabUtility.LoadPrefabContents(rig);
            try
            {
                var hands=root.GetComponentsInChildren<Hand>(true).Where(h=>h.name==handsName).ToArray();
                Assert.AreEqual(2,hands.Length,"a hand a side on "+handsName);
                foreach(var hand in hands)
                {
                    Assert.AreEqual(raw,MetaShadowPlayer.RawSource(hand).GetType().Name,"the chain starts at the runtime's hand tracking");
                    Assert.IsTrue(Chain(hand).Any(s=>s is LastKnownGoodHand),"and runs through LastKnownGoodHand");
                }
                int made=root.GetComponentsInChildren<Hand>(true).Count(h=>MetaShadowPlayer.RawSource(h) is ControllerHandDataSource);
                if(controllerHands)Assert.Greater(made,0,"controller-made hands root at ControllerHandDataSource");
            }
            finally{PrefabUtility.UnloadPrefabContents(root);}
        }
        static IEnumerable<IDataSource<HandDataAsset>> Chain(IDataSource<HandDataAsset> s)
        {
            for(int i=0;i<16&&s!=null;i++){yield return s;var m=s as DataModifier<HandDataAsset>;s=m!=null?m.ModifyDataFromSource:null;}
        }
    }
}
