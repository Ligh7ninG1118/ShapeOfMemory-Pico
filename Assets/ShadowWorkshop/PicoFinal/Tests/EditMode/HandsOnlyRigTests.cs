using System.Linq;
using System.Reflection;
using CloudGarden.Integration;
using NUnit.Framework;
using UnityEditor;
using UnityEngine;

namespace ShapeOfMemory.Tests
{
    // The 2026-11-07 playtest: an idle right controller left on counted as connected, which turned that hand's ray off for
    // the whole session and swapped in the controller's poke whenever the hand dropped out. HandsOnly rewires the rig so a
    // hand never yields to a controller. Checked on the generated PICO player, opened as prefab contents (not in a scene).
    public class HandsOnlyRigTests
    {
        const string Rig="Assets/MetaHackthone/Generated/PicoPlayer.prefab";

        [Test] public void AControllerNeverTakesASideFromItsHand()
        {
            if(!AssetDatabase.LoadAssetAtPath<GameObject>(Rig))Assert.Ignore("PicoPlayer.prefab is generated by the Pico build");
            var root=PrefabUtility.LoadPrefabContents(Rig);
            try
            {
                Assert.AreEqual(8,MetaShadowPlayer.HandsOnly(root.transform),"per side: the hand-and-no-controller tracker and three controller trackers");
                int hands=0,controllers=0;
                foreach(var t in root.GetComponentsInChildren<Transform>(true))
                {
                    if(!t.parent||t.parent.name!="ActiveStatesTrackers")continue;
                    var tracker=t.GetComponents<MonoBehaviour>().First(m=>m&&m.GetType().Name=="ActiveStateTracker");
                    var dependents=t.parent.parent.Find(t.name);
                    if(t.name.StartsWith("Controller"))
                    {
                        controllers++;Assert.IsFalse(tracker.enabled,t.name+" tracker is off");
                        Assert.IsFalse(dependents.gameObject.activeSelf,t.name+" interactors stay off");
                    }
                    else if(t.name=="Hand and No Controller")
                    {
                        hands++;var state=tracker.GetType().GetField("_activeState",BindingFlags.Instance|BindingFlags.NonPublic).GetValue(tracker);
                        Assert.AreEqual("HandRef",state.GetType().Name,"the hand ray follows the hand alone");
                    }
                }
                Assert.AreEqual(2,hands);Assert.AreEqual(6,controllers);
            }
            finally{PrefabUtility.UnloadPrefabContents(root);}
        }
    }
}
